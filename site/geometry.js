/** Pure polygon containment is also used by the non-browser geometry tests. */
const parsedPaths = new Map();
function verticesFor(path) {
  if(!parsedPaths.has(path)) parsedPaths.set(path,path.split('M').slice(1).map(sub=>sub.replace('Z','').split('L').map(p=>p.trim().split(/\s+/).map(Number))));
  return parsedPaths.get(path);
}
export function contains(path, x, y) {
  let inside = false;
  for (const vertices of verticesFor(path)) {
    let part = false;
    for (let i = 0, j = vertices.length - 1; i < vertices.length; j = i++) {
      const [xi, yi] = vertices[i], [xj, yj] = vertices[j];
      if ((yi > y) !== (yj > y) && x < (xj-xi)*(y-yi)/(yj-yi)+xi) part = !part;
    }
    inside ||= part;
  }
  return inside;
}
// Frontend's foreground sneaker wins its small overlap with the creator's shoe.
export const HIT_ORDER = [0, 1, 3, 4, 2];
export function hitRole(x, y) {
  if (ENVIRONMENT.some(path => contains(path, x, y))) return -1;
  for (const i of HIT_ORDER) if (contains(ROLES[i].silhouette, x, y) || contains(ROLES[i].lower, x, y)) return i;
  return -1;
}

export function nearbyRole(x,y,padding=0) {
  const exact=hitRole(x,y);
  if(exact>=0||padding<=0||y>350||ENVIRONMENT.some(p=>contains(p,x,y)))return exact;
  let nearest=-1,best=padding*padding;
  for(const i of HIT_ORDER)for(const vertices of verticesFor(ROLES[i].silhouette))for(let j=0;j<vertices.length;j++){
    const a=vertices[j],b=vertices[(j+1)%vertices.length],dx=b[0]-a[0],dy=b[1]-a[1];
    const t=Math.max(0,Math.min(1,((x-a[0])*dx+(y-a[1])*dy)/(dx*dx+dy*dy||1)));
    const d=(x-a[0]-t*dx)**2+(y-a[1]-t*dy)**2;
    if(d<best){best=d;nearest=i;}
  }
  return nearest;
}
/** Sample a pointer segment, including a fast pass whose final point is outside. */
export function sweepRoles(from,to,padding=0){
  const steps=Math.min(300,Math.max(1,Math.ceil(Math.hypot(to[0]-from[0],to[1]-from[1])/12)));
  const result=[];
  for(let n=0;n<=steps;n++){
    const t=n/steps,x=from[0]+(to[0]-from[0])*t,y=from[1]+(to[1]-from[1])*t;
    if(x< -padding||y< -padding||x>WIDTH+padding||y>HEIGHT+padding)continue;
    const role=nearbyRole(x,y,padding);
    if(role>=0&&result.at(-1)!==role)result.push(role);
  }
  return result;
}
